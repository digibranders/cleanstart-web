const collectWebflowFields = async (jsonlFile: string): Promise<Set<string>> => {
  const fields = new Set<string>();
  if (!fs.existsSync(jsonlFile)) return fields;

  const rl = readline.createInterface({ input: fs.createReadStream(jsonlFile) });
  let lines = 0;
  for await (const line of rl) {
    if (lines > 20) break; // sample first 20 rows
    lines += 1;
    try {
      const row = JSON.parse(line) as Record<string, unknown>;
      for (const key of Object.keys(row)) {
        if (!['collection', 'webflowId', 'id'].includes(key)) fields.add(key);
      }
    } catch {
      // ignore malformed lines
    }
  }
  return fields;
};

const run = async (): Promise<void> => {
  console.log('[schema-parity] Generating audit…');

  const lines: string[] = [
    '# Schema Parity Audit — Webflow → Payload',
    '',
    '_Auto-generated by `migrations/webflow-import/schema-parity-audit.ts`._',
    '',
    'Status key: **mapped** = explicit mapping exists | **missing** = no Payload field found | **dropped** = intentionally excluded | **new** = Payload field with no Webflow source',
    '',
  ];

  const collectionSlugs = Object.keys(FIELD_MAP);

  for (const slug of collectionSlugs) {
    const jsonlFile = path.join(RAW_DIR, `${slug}.jsonl`);
    const webflowFields = await collectWebflowFields(jsonlFile);
    const mappings = FIELD_MAP[slug] ?? {};

    lines.push(`## ${slug}`, '');
    lines.push('| Webflow field | Payload field | Status |');
    lines.push('|---|---|---|');

    // Fields from JSONL sample
    const allWebflowFields = new Set([...Object.keys(mappings), ...webflowFields]);
    for (const wfField of allWebflowFields) {
      const payloadField = mappings[wfField];
      if (payloadField === undefined) {
        lines.push(`| \`${wfField}\` | — | **missing** |`);
      } else if (payloadField === null) {
        lines.push(`| \`${wfField}\` | _(dropped)_ | **dropped** |`);
      } else {
        lines.push(`| \`${wfField}\` | \`${payloadField}\` | **mapped** |`);
      }
    }
    lines.push('');
  }

  fs.writeFileSync(OUT_FILE, lines.join('\n'));
  console.log(`[schema-parity] Written to ${OUT_FILE}`);
};

run().catch((err) => {
  console.error('[schema-parity] Fatal:', err);
  process.exit(1);
});
