/**
 * H2 — Schema parity audit
 *
 * Compares Webflow field names (from exported JSONL sample) against
 * Payload collection field names and writes a markdown table.
 *
 * Usage:
 *   tsx migrations/webflow-import/schema-parity-audit.ts
 *
 * Input:  migrations/webflow-export/raw/<collection>.jsonl
 * Output: migrations/SCHEMA-PARITY-AUDIT.md
 */

